import express from 'express';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import swaggerUi from 'swagger-ui-express';
import { z } from 'zod';
import { SIBH_WINDOWS } from '@chuvas/hydrology';
const sibhHours=z.coerce.number().int().refine(n=>SIBH_WINDOWS.includes(n),'Janela deve ser 1, 2, 3, 6, 12, 24, 48 ou 72 horas.').default(1);
import { db } from './db.js';
import { BASE,config } from './config.js';
import { requireAuth,requireAdmin } from './middleware/auth.js';
import * as auth from './controllers/auth-controller.js';
import * as idf from './controllers/idf-controller.js';
import * as spatial from './controllers/spatial-controller.js';
import * as families from './controllers/family-controller.js';
import * as branding from './controllers/branding-controller.js';
import * as sgbSettings from './controllers/sgb-settings-controller.js';
import { sgbRuntimeStatus } from './services/sgb-settings-service.js';
import * as catalog from './repositories/catalog-repository.js';
import { publishEquation } from './services/equation-service.js';
import { integrationStatus,latestObservations } from './services/sibh-service.js';
import { openapi } from './openapi.js';
import { sgbCatalog,sgbStatus } from './repositories/sgb-repository.js';
export const app=express();
app.disable('x-powered-by');app.set('trust proxy','loopback, linklocal, uniquelocal');
app.use(helmet({contentSecurityPolicy:false}));
app.use(`${BASE}/api`,rateLimit({windowMs:60000,limit:300,standardHeaders:'draft-8',legacyHeaders:false}));
app.put(`${BASE}/api/admin/branding`,requireAuth,requireAdmin,express.json({limit:'2mb'}),branding.save);
app.use(express.json({limit:'256kb'}));
const api=express.Router();
api.get('/branding',branding.settings);
api.get('/branding/:kind', (req,res,next)=>['logo','favicon'].includes(req.params.kind)?branding.image(req,res).catch(next):next());
api.get('/admin/branding',requireAuth,requireAdmin,branding.adminSettings);
api.get('/health',async(req,res)=>{try{await db.raw('SELECT 1');res.json({status:'ok'});}catch{res.status(503).json({status:'unavailable'});}});
api.post('/auth/login',rateLimit({windowMs:15*60000,limit:15,skipSuccessfulRequests:true,standardHeaders:'draft-8',legacyHeaders:false,message:{error:'Muitas tentativas. Aguarde 15 minutos.'}}),auth.login);
api.get('/auth/me',requireAuth,(req,res)=>res.json(req.user));
api.post('/auth/logout',requireAuth,auth.logout);
api.get('/municipalities',async(req,res)=>res.json(await catalog.listMunicipalities()));
api.get('/municipalities/:id/equation',async(req,res)=>{const e=await catalog.getMunicipalityEquation(req.params.id);if(!e)return res.status(404).json({error:'Equação não encontrada.'});res.json(e);});
api.post('/idf/calculate',idf.calculation);api.post('/idf/return-period',idf.inverse);api.get('/idf/curves',idf.curves);
api.post('/idf/spatial-return-period',spatial.spatialEstimate);
api.get('/spatial/reference-stations',spatial.referenceStations);
api.get('/spatial/municipalities',spatial.boundaries);
api.get('/observations',async(req,res)=>{const filters=z.object({hours:sibhHours,municipality_id:z.string().regex(/^35\d{5}$/).optional(),limit:z.coerce.number().int().min(1).max(2000).default(100),offset:z.coerce.number().int().min(0).max(20000).default(0)}).parse(req.query);res.json(await latestObservations(filters));});
api.get('/integration/status',async(req,res)=>res.json(await integrationStatus(sibhHours.parse(req.query.hours))));
api.get('/admin/equations',requireAuth,async(req,res)=>res.json(await catalog.listEquations()));
api.get('/admin/equation-families',requireAuth,families.list);
api.post('/admin/equation-families/preview',requireAuth,families.preview);
api.post('/admin/equation-families',requireAuth,families.create);
api.put('/admin/equation-families/:code',requireAuth,families.revise);
api.patch('/admin/equation-families/:code/status',requireAuth,requireAdmin,families.status);
api.get('/admin/equations/:id',requireAuth,async(req,res)=>{const e=await catalog.getEquation(req.params.id);if(!e)return res.status(404).json({error:'Equação não encontrada.'});res.json(e);});
api.post('/admin/equations',requireAuth,async(req,res)=>res.status(201).json(await publishEquation(req.body,req.user.id)));
api.put('/admin/equations/:id',requireAuth,async(req,res)=>{const old=await catalog.getEquation(req.params.id);if(!old)return res.status(404).json({error:'Equação não encontrada.'});if(req.body.municipality_id!==old.municipality_id)return res.status(422).json({error:'Uma revisão deve pertencer ao mesmo município.'});res.status(201).json(await publishEquation(req.body,req.user.id));});
api.delete('/admin/equations/:id',requireAuth,requireAdmin,async(req,res)=>{await catalog.retireEquation(req.params.id,req.user.id);res.status(204).end();});
api.get('/admin/integration/runs',requireAuth,async(req,res)=>res.json(await db('integration_runs').orderBy('started_at','desc').limit(100)));
api.get('/admin/sgb/publications',requireAuth,async(req,res)=>{const filters=z.object({year:z.coerce.number().int().min(1900).max(2200).optional(),municipality_id:z.string().regex(/^35\d{5}$/).optional()}).parse(req.query);res.json(await sgbCatalog(filters));});
api.get('/admin/sgb/settings',requireAuth,requireAdmin,sgbSettings.settings);
api.put('/admin/sgb/settings',requireAuth,requireAdmin,sgbSettings.save);
api.get('/admin/sgb/status',requireAuth,async(req,res)=>{const [catalog,runtime]=await Promise.all([sgbStatus(),sgbRuntimeStatus()]);res.set('Cache-Control','no-store').json({...catalog,...runtime})});
api.get('/admin/sgb/runs',requireAuth,async(req,res)=>res.json(await db('sgb_sync_runs').orderBy('started_at','desc').limit(100)));
api.get('/admin/audit',requireAuth,requireAdmin,async(req,res)=>res.json(await db('audit_logs').orderBy('created_at','desc').limit(100)));
api.get('/openapi.json',(req,res)=>res.json(openapi));
app.use(`${BASE}/api`,api);
app.use(`${BASE}/docs`,swaggerUi.serve,swaggerUi.setup(openapi,{swaggerOptions:{persistAuthorization:false}}));
app.get(`${BASE}/source/estudo.pdf`,(req,res)=>res.sendFile(new URL('../../../docs/source/estudo-daee-cth.pdf',import.meta.url).pathname));
app.use((req,res)=>res.status(404).json({error:'Rota não encontrada.'}));
app.use((error,req,res,next)=>{
 if(error instanceof z.ZodError)return res.status(422).json({error:'Dados inválidos.',details:error.issues.map(i=>({path:i.path.join('.'),message:i.message}))});
 if(error.type==='entity.parse.failed')return res.status(400).json({error:'JSON inválido.'});
 const status=error.status||500;if(status===500)console.error(JSON.stringify({event:'api.error',message:error.message}));
 res.status(status).json({error:status>=500?'Falha interna ao processar a solicitação.':error.message,code:error.code});
});
